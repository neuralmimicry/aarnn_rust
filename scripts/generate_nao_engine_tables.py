"""OEM NAO tables for the Unity and Unreal legacy NAO bodies.

The MuJoCo reference NAO (scripts/embodiment_legacy.py nao_body, OEM drives in
scripts/embodiment_neural.py nao_joint) is generated into
sim/content/embodiments/generated/nao.json and the engine-neutral rigid graph
sim/content/embodiments/graphs/nao.json. The legacy game-engine bodies do not
load either file at run time, so this script freezes what they need into one
C# and one C++ table: the link tree in the OEM zero pose (offsets, joint axes,
masses, inertia, one collision primitive per link), each joint's OEM range,
torque, speed and position-servo gains, and the actuator contract (output
names, readout channel, decode_tau_s, wake).

  python3 scripts/generate_nao_engine_tables.py          # write
  python3 scripts/generate_nao_engine_tables.py --check  # verify current
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / 'sim/content/embodiments/generated/nao.json'
GRAPH = ROOT / 'sim/content/embodiments/graphs/nao.json'
UNITY = ROOT / 'sim/unity/Assets/NeuralMimicry/Runtime/Robots/NmNaoOem.generated.cs'
UNREAL = ROOT / 'sim/unreal/Source/NmAerBridge/Public/Robots/NmNaoOem.generated.h'
# MuJoCo geom types used by the NAO record.
GEOM = {2: 'Sphere', 3: 'Capsule', 4: 'Ellipsoid', 5: 'Cylinder', 6: 'Box'}


def num(v):
    v = float(v)
    text = repr(v)
    return text if ('.' in text or 'e' in text or 'n' in text) else text + '.0'


def vec(values):
    return ', '.join(num(v) for v in values)


def tables():
    record = json.loads(RECORD.read_text())
    graph = json.loads(GRAPH.read_text())
    if record['profile_id'] != 'nao' or graph['profile_id'] != 'nao' or graph['model_digest'] != record['digest']:
        raise SystemExit('nao record/graph mismatch: regenerate the embodiment products first')
    bodies = record['bodies']
    joints = {j['body']: j for j in record['joints'] if j['type'] == 3}
    actuators = {a['joint']: (i, a) for i, a in enumerate(record['actuators'])}
    targets = {t['joint']: t for t in graph['targets']}
    collision = {}
    for g in record['geoms']:
        if g.get('collision') and g['body'] > 0:
            collision.setdefault(g['body'], g)
    if bodies[0]['name'] != 'torso' or any(b['quaternion_wxyz'] != [1.0, 0.0, 0.0, 0.0] for b in bodies):
        raise SystemExit('NAO links must be built in the OEM zero pose (identity body frames)')
    links = []
    for body_id, b in enumerate(bodies[1:], start=2):
        j = joints[body_id]
        index, a = actuators[j['name']]
        t = targets[j['name']]
        if len(a['readout']) != 1 or a['readout'][0]['coefficient'] != 1.0 or not a['position_readout']:
            raise SystemExit(f"{a['name']}: one unit position readout expected")
        if a['control_range'] != j['range'] or index != body_id - 2:
            raise SystemExit(f"{a['name']}: actuator order/range differs from the link tree")
        g = collision[body_id]
        if g['type'] not in GEOM:
            raise SystemExit(f"{g['name']}: unsupported collision type {g['type']}")
        wake = a.get('wake') or {}
        links.append(dict(
            name=a['name'], parent=b['parent'] - 2, position=b['position'], axis=j['axis'],
            lo=a['control_range'][0], hi=a['control_range'][1], effort=a['effort_range'][1],
            velocity=a['velocity_limit'], kp=t['gain'], kd=t['damping'], channel=a['readout'][0]['channel'],
            wake=bool(wake), wake_from=wake.get('from', 0.0), wake_seconds=wake.get('seconds', 0.0),
            decode_tau=a.get('decode_tau_s') or 0.0, mass=b['mass_kg'], com=b['com_m'],
            inertia=b['diagonal_inertia_kgm2'], inertia_frame=b['inertia_orientation_wxyz'],
            shape=GEOM[g['type']], shape_position=g['position'], shape_frame=g['quaternion_wxyz'],
            shape_half=(list(g['half_size_m']) + [0.0, 0.0, 0.0])[:3]))
    torso = bodies[0]
    tg = collision[1]
    meta = dict(digest=record['digest'], io_digest=record['io']['digest'], outputs=record['io']['output_names'],
                total=record['total_mass_kg'], torso_mass=torso['mass_kg'], torso_com=torso['com_m'],
                torso_inertia=torso['diagonal_inertia_kgm2'], torso_frame=torso['inertia_orientation_wxyz'],
                torso_height=torso['world_position'][2], torso_box_position=tg['position'], torso_box_half=tg['half_size_m'],
                sensors=len(record['io']['sensors']))
    if tg['type'] != 6 or len(meta['outputs']) != len(links):
        raise SystemExit('NAO torso box / 40-output contract changed: update the engine bodies')
    return meta, links


HEADER = ('Generated by scripts/generate_nao_engine_tables.py from\n'
          'sim/content/embodiments/generated/nao.json and graphs/nao.json; do not edit.\n'
          'MuJoCo frame (x forward, y left, z up; metres, kg, rad, N m, s), OEM zero\n'
          'pose: every link frame is parallel to the torso; joint angle 0 = built pose.\n'
          'Drives: kp = OEM joint torque / 0.1 rad, kd = back-EMF damping (torque / speed).\n')


def unity(meta, links):
    rows = []
    for k in links:
        rows.append(
            f'            new Link("{k["name"]}", {k["parent"]}, {k["channel"]}, new[] {{ {vec(k["position"])} }}, '
            f'new[] {{ {vec(k["axis"])} }}, {num(k["lo"])}, {num(k["hi"])}, {num(k["effort"])}, {num(k["velocity"])}, '
            f'{num(k["kp"])}, {num(k["kd"])}, {num(k["mass"])}, new[] {{ {vec(k["com"])} }}, new[] {{ {vec(k["inertia"])} }}, '
            f'new[] {{ {vec(k["inertia_frame"])} }}, Shape.{k["shape"]}, new[] {{ {vec(k["shape_position"])} }}, '
            f'new[] {{ {vec(k["shape_frame"])} }}, new[] {{ {vec(k["shape_half"])} }}, {str(k["wake"]).lower()}, '
            f'{num(k["wake_from"])}, {num(k["wake_seconds"])}, {num(k["decode_tau"])}),')
    outputs = ',\n'.join(f'            "{n}"' for n in meta['outputs'])
    head = ''.join('// ' + line + '\n' for line in HEADER.splitlines())
    return f'''// SPDX-FileCopyrightText: masterkiga
// SPDX-License-Identifier: MIT
//
{head}
namespace NeuralMimicry
{{
    /// <summary>OEM NAO (Aldebaran H25 V6) link tree and actuator contract.</summary>
    internal static class NmNaoOem
    {{
        public const string ModelDigest = "{meta['digest']}";
        public const string IoDigest = "{meta['io_digest']}";
        public const int SensorCount = {meta['sensors']};
        public const double TotalMassKg = {num(meta['total'])};
        public const double TorsoMassKg = {num(meta['torso_mass'])};
        public static readonly double[] TorsoComM = {{ {vec(meta['torso_com'])} }};
        public static readonly double[] TorsoInertiaKgM2 = {{ {vec(meta['torso_inertia'])} }};
        public static readonly double[] TorsoInertiaFrameWxyz = {{ {vec(meta['torso_frame'])} }};
        /// <summary>Torso origin height of the standing built pose (soles 2 mm above ground).</summary>
        public const double TorsoHeightM = {num(meta['torso_height'])};
        public static readonly double[] TorsoBoxPositionM = {{ {vec(meta['torso_box_position'])} }};
        public static readonly double[] TorsoBoxHalfM = {{ {vec(meta['torso_box_half'])} }};

        public enum Shape {{ Sphere, Capsule, Ellipsoid, Cylinder, Box }}

        /// <summary>One hinge link; table order = actuator order of the record.</summary>
        public sealed class Link
        {{
            public readonly string Name;
            /// <summary>Parent link index; -1 = torso.</summary>
            public readonly int Parent;
            /// <summary>Brain output channel of this joint's position readout.</summary>
            public readonly int Channel;
            public readonly double[] PositionM, Axis;
            public readonly double Lo, Hi, EffortNm, VelocityRadS, Kp, Kd, MassKg;
            public readonly double[] ComM, InertiaKgM2, InertiaFrameWxyz;
            public readonly Shape Collider;
            public readonly double[] ColliderPositionM, ColliderFrameWxyz, ColliderHalfM;
            public readonly bool Wake;
            public readonly double WakeFrom, WakeSeconds;
            /// <summary>Graded decode time constant (s); 0 = default (motor RATE_TAU_S).</summary>
            public readonly double DecodeTauS;

            public Link(string name, int parent, int channel, double[] position, double[] axis, double lo, double hi,
                        double effort, double velocity, double kp, double kd, double mass, double[] com, double[] inertia,
                        double[] inertiaFrame, Shape collider, double[] colliderPosition, double[] colliderFrame,
                        double[] colliderHalf, bool wake, double wakeFrom, double wakeSeconds, double decodeTau)
            {{
                Name = name; Parent = parent; Channel = channel; PositionM = position; Axis = axis; Lo = lo; Hi = hi;
                EffortNm = effort; VelocityRadS = velocity; Kp = kp; Kd = kd; MassKg = mass; ComM = com;
                InertiaKgM2 = inertia; InertiaFrameWxyz = inertiaFrame; Collider = collider;
                ColliderPositionM = colliderPosition; ColliderFrameWxyz = colliderFrame; ColliderHalfM = colliderHalf;
                Wake = wake; WakeFrom = wakeFrom; WakeSeconds = wakeSeconds; DecodeTauS = decodeTau;
            }}
        }}

        public static readonly Link[] Links =
        {{
{chr(10).join(rows)}
        }};

        /// <summary>Brain output channel names (io.output_names).</summary>
        public static readonly string[] OutputNames =
        {{
{outputs},
        }};
    }}
}}
'''


def unreal(meta, links):
    rows = []
    for k in links:
        rows.append(
            f'    {{TEXT("{k["name"]}"), {k["parent"]}, {k["channel"]}, {{{vec(k["position"])}}}, {{{vec(k["axis"])}}}, '
            f'{num(k["lo"])}, {num(k["hi"])}, {num(k["effort"])}, {num(k["velocity"])}, {num(k["kp"])}, {num(k["kd"])}, '
            f'{num(k["mass"])}, {{{vec(k["com"])}}}, {{{vec(k["inertia"])}}}, EShape::{k["shape"]}, '
            f'{{{vec(k["shape_position"])}}}, {{{vec(k["shape_frame"])}}}, {{{vec(k["shape_half"])}}}, '
            f'{str(k["wake"]).lower()}, {num(k["wake_from"])}, {num(k["wake_seconds"])}, {num(k["decode_tau"])}}},')
    outputs = '\n'.join(f'    TEXT("{n}"),' for n in meta['outputs'])
    head = ''.join('// ' + line + '\n' for line in HEADER.splitlines())
    return f'''// SPDX-FileCopyrightText: masterkiga
// SPDX-License-Identifier: MIT
//
{head}#pragma once

#include "CoreMinimal.h"

namespace NmNaoOem
{{
inline constexpr const TCHAR* ModelDigest = TEXT("{meta['digest']}");
inline constexpr const TCHAR* IoDigest = TEXT("{meta['io_digest']}");
inline constexpr int32 SensorCount = {meta['sensors']};
inline constexpr double TotalMassKg = {num(meta['total'])};
inline constexpr double TorsoMassKg = {num(meta['torso_mass'])};
inline constexpr double TorsoComM[3] = {{{vec(meta['torso_com'])}}};
/** Torso origin height of the standing built pose (soles 2 mm above ground). */
inline constexpr double TorsoHeightM = {num(meta['torso_height'])};
inline constexpr double TorsoBoxPositionM[3] = {{{vec(meta['torso_box_position'])}}};
inline constexpr double TorsoBoxHalfM[3] = {{{vec(meta['torso_box_half'])}}};

enum class EShape : uint8 {{ Sphere, Capsule, Ellipsoid, Cylinder, Box }};

/** One hinge link; table order = actuator order of the record. */
struct FLink
{{
    const TCHAR* Name;
    int32 Parent;   // parent link index; -1 = torso
    int32 Channel;  // brain output channel of this joint's position readout
    double PositionM[3];
    double Axis[3];
    double Lo, Hi, EffortNm, VelocityRadS, Kp, Kd, MassKg;
    double ComM[3];
    double InertiaKgM2[3];
    EShape Collider;
    double ColliderPositionM[3];
    double ColliderFrameWxyz[4];
    double ColliderHalfM[3];
    bool bWake;
    double WakeFrom, WakeSeconds;
    double DecodeTauS; // graded decode time constant (s); 0 = default (motor RATE_TAU_S)
}};

inline constexpr int32 NumLinks = {len(links)};
inline constexpr FLink Links[NumLinks] = {{
{chr(10).join(rows)}
}};

/** Brain output channel names (io.output_names). */
inline constexpr const TCHAR* OutputNames[NumLinks] = {{
{outputs}
}};
}} // namespace NmNaoOem
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if a generated table is stale')
    args = parser.parse_args()
    meta, links = tables()
    stale = []
    for path, text in ((UNITY, unity(meta, links)), (UNREAL, unreal(meta, links))):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        tmp = path.with_name(path.name + '.tmp')
        tmp.write_text(text)
        tmp.replace(path)
        print('wrote', path.relative_to(ROOT))
    if stale:
        print('stale (run scripts/generate_nao_engine_tables.py):', ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
