#!/usr/bin/env python3
"""Generate the deliberately small C/C# ABI directly from Rust export signatures.

Rejects any new type/syntax until its ABI mapping has been reviewed. No parallel
hand-authored function list: the Rust public exports and constants are authority.
"""
import argparse
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'crates/aarnn-embodiment-ffi/src/lib.rs'
HEADER=ROOT/'crates/aarnn-embodiment-ffi/include/nm_embodiment.h'
CS=ROOT/'sim/unity/Assets/NeuralMimicry/Runtime/Embodiment/EmbodimentNative.generated.cs'
SCALARS={'u32':('uint32_t','uint'),'u64':('uint64_t','ulong'),'i32':('int32_t','int')}
POINTERS={'*const u8':('const uint8_t*','[In] byte[]'),'*mut u8':('uint8_t*','[Out] byte[]'),'*const f64':('const double*','[In] double[]'),'*mut f64':('double*','[Out] double[]'),'*mut u64':('uint64_t*','out ulong')}
def products():
    source=SOURCE.read_text()
    pattern=r'#\[unsafe\(no_mangle\)\]\s*pub (?:unsafe )?extern "C" fn (\w+)\s*\((.*?)\)\s*->\s*(\w+)\s*\{'
    exports=re.findall(pattern,source,re.S)
    if len(exports)!=source.count('#[unsafe(no_mangle)]'):raise ValueError('unrecognised ABI declaration')
    h=['// Generated by scripts/generate_embodiment_ffi.py; do not edit.','#pragma once','#include <stdint.h>','#ifdef __cplusplus','extern "C" {','#endif']
    c=['// Generated by scripts/generate_embodiment_ffi.py; do not edit.','using System.Runtime.InteropServices;','namespace NeuralMimicry {','internal static class EmbodimentNative {','    const string Library = "aarnn_embodiment_ffi";']
    for name,value in re.findall(r'pub const (NM_\w+): u32 = (\d+);',source):
        h.append(f'#define {name} {value}u');c.append(f'    internal const uint {name} = {value};')
    for name,args,ret in exports:
        params=[]
        for arg in args.split(','):
            if arg.strip():
                param,kind=arg.strip().split(':',1);kind=kind.strip()
                mapped=(SCALARS|POINTERS)[kind];params.append((param,*mapped))
        h.append(f'{SCALARS[ret][0]} {name}('+(', '.join(f'{ty} {p}' for p,ty,_ in params) or 'void')+');')
        c+=['    [DllImport(Library, CallingConvention = CallingConvention.Cdecl)]',f'    internal static extern {SCALARS[ret][1]} {name}('+', '.join(f'{ty} {p}' for p,_,ty in params)+');']
    h+=['#ifdef __cplusplus','}','#endif','// All buffers are caller-owned for the call, aligned, non-overlapping and','// sized by the explicit element counts. Negative results require disarm.','// AER1 reference operations confer no production permission or commit proof.']
    c+=['}','}']
    return {HEADER:'\n'.join(h)+'\n',CS:'\n'.join(c)+'\n'}
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,text in products().items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('stale generated ABI '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    print('Embodiment ABI bindings verified' if args.check else 'Embodiment ABI bindings generated')
if __name__=='__main__':main()
