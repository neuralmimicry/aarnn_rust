//! Generator (and staleness check) of the salamander crawler open-loop
//! functional contract from the body's IO contract (G2), plus its
//! learned-state extension (`salamander_learned.toml`: the eight 1 s
//! conditions and three that exercise learned foraging, for a
//! `derive --preset learned-cap` source; the slow exploration task is left to
//! the profile's declared protection). Regenerate with:
//! `AARNN_EXPLORER_WRITE_FIXTURE=1 cargo test -p aarnn-explorer --test gen_salamander_suite`.
use std::fmt::Write;

const IO: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../sim/content/embodiments/generated/salamander_crawler.json"
);
const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../examples/explorer/tasks/salamander_open_loop.toml"
);
const OUT_LEARNED: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../examples/explorer/tasks/salamander_learned.toml"
);

fn suite(learned: bool) -> String {
    let io: serde_json::Value = serde_json::from_slice(&std::fs::read(IO).unwrap()).unwrap();
    let outputs: Vec<String> = io["io"]["output_names"]
        .as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_str().unwrap().to_string())
        .collect();
    let mut s = String::new();
    s += "# SPDX-FileCopyrightText: masterkiga\n# SPDX-License-Identifier: MIT\n#\n# Licensed under the MIT License. See LICENSE in the project root.\n#\n";
    s += "# GENERATED by crates/aarnn-explorer/tests/gen_salamander_suite.rs from the salamander_crawler IO\n";
    s += "# contract. Open-loop functional contract of the composed salamander crawler\n";
    s += "# circuit (G2): in each condition, every one of the 22 motor outputs' mean\n";
    s += "# activation must stay within 10 % (+ 0.02) of the intact reference (cold start,\n";
    s += "# frozen plasticity). Conditions: walking, obstacles left/right (range 0.3),\n";
    s += "# touch left/right/front (escape C-bend), feeding (halt) and hungry with a\n";
    s += "# left odour cue. A simulated-body contract, not a claim about animal behaviour.\n";
    if learned {
        s += "# Learned-state extension: hungry with a right cue, sated with a left cue (the\n";
        s += "# hunger gate) and a hungry cue that falls after 2 s (the value-fall turn), for\n";
        s += "# a learned-state source (aarnn-explorer derive --preset learned-cap). No 20 s\n";
        s += "# exploration task: the slow rhythms are declared protected by the profile.\n";
    }
    let name = if learned {
        "salamander-learned-v1"
    } else {
        "salamander-open-loop-v1"
    };
    let _ = write!(
        s,
        "schema_version = 1\nname = \"{name}\"\n\n[splits]\ndevelopment = [1, 2, 3, 4]\nlocked_validation = [101, 102, 103, 104]\n"
    );
    let sated = "{ channel = \"needs_energy\", start_ms = 0, end_ms = 1000, value = 0.9 }";
    let mut tasks: Vec<(&str, &str, Vec<String>, (u32, u32))> = vec![
        ("walk", "discrimination", vec![sated.into()], (200, 1000)),
        ("obstacle-left", "discrimination", vec![sated.into(), "{ channel = \"sal_s_26_prox_02\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into(), "{ channel = \"sal_s_25_prox_01\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into()], (300, 800)),
        ("obstacle-right", "discrimination", vec![sated.into(), "{ channel = \"sal_s_38_prox_14\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into(), "{ channel = \"sal_s_39_prox_15\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into()], (300, 800)),
        ("touch-left", "timing", vec![sated.into(), "{ channel = \"sal_s_22_touch_left\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"sal_s_26_prox_02\", start_ms = 300, end_ms = 500, value = 0.95, jitter = true }".into()], (300, 1000)),
        ("touch-right", "timing", vec![sated.into(), "{ channel = \"sal_s_23_touch_right\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"sal_s_38_prox_14\", start_ms = 300, end_ms = 500, value = 0.95, jitter = true }".into()], (300, 1000)),
        ("touch-front", "timing", vec![sated.into(), "{ channel = \"sal_s_21_touch_front\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"sal_s_24_prox_00\", start_ms = 300, end_ms = 500, value = 0.95, jitter = true }".into()], (300, 1000)),
        ("feeding", "discrimination", vec![sated.into(), "{ channel = \"needs_consume\", start_ms = 300, end_ms = 700, value = 1.0, jitter = true }".into()], (300, 700)),
        ("hungry-cue-left", "discrimination", vec!["{ channel = \"needs_energy\", start_ms = 0, end_ms = 1000, value = 0.2 }".into(), "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.8 }".into(), "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.2 }".into()], (200, 1000)),
        // Slow behaviour: the ARTR exploration oscillator alternates every
        // 10-20 s, invisible in 1 s trials (a reduction under the 1 s
        // contract removed ARTR_r). A 20 s walk covers it.
        ("explore-20s", "timing", vec!["{ channel = \"needs_energy\", start_ms = 0, end_ms = 20000, value = 0.9 }".into()], (2000, 20000)),
    ];
    if learned {
        tasks.retain(|t| t.0 != "explore-20s");
        let hungry = |ms: u32| {
            format!("{{ channel = \"needs_energy\", start_ms = 0, end_ms = {ms}, value = 0.2 }}")
        };
        tasks.push((
            "hungry-cue-right",
            "discrimination",
            vec![
                hungry(1000),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.8 }"
                    .into(),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.2 }".into(),
            ],
            (200, 1000),
        ));
        tasks.push((
            "sated-cue-left",
            "discrimination",
            vec![
                sated.into(),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.8 }".into(),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.2 }"
                    .into(),
            ],
            (200, 1000),
        ));
        tasks.push((
            "hungry-cue-fall",
            "timing",
            vec![
                hungry(3000),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 2000, value = 0.8 }".into(),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 2000, value = 0.8 }"
                    .into(),
                "{ channel = \"needs_cue_left\", start_ms = 2000, end_ms = 3000, value = 0.1 }"
                    .into(),
                "{ channel = \"needs_cue_right\", start_ms = 2000, end_ms = 3000, value = 0.1 }"
                    .into(),
            ],
            (2000, 3000),
        ));
    }
    for (id, fam, stim, (a, b)) in tasks {
        let dur = b.max(1000);
        let _ = write!(
            s,
            "\n[[task]]\nid = \"{id}\"\nfamily = \"{fam}\"\nduration_ms = {dur}\njitter_ms = 4\nstimulus = [\n"
        );
        for x in &stim {
            let _ = writeln!(s, "  {x},");
        }
        s += "]\nmeasure = [\n";
        for (k, o) in outputs.iter().enumerate() {
            let _ = writeln!(
                s,
                "  {{ name = \"m{k:02}\", output = \"{o}\", start_ms = {a}, end_ms = {b}, stat = \"mean\" }},"
            );
        }
        s += "]\ncriterion = [\n";
        for k in 0..outputs.len() {
            let _ = writeln!(
                s,
                "  {{ measure = \"m{k:02}\", op = \"within-reference\", amount = 0.1, value = 0.02 }},"
            );
        }
        s += "]\n";
    }
    s
}

#[test]
fn salamander_suite_is_current() {
    check(false, OUT);
}

#[test]
fn salamander_learned_suite_is_current() {
    check(true, OUT_LEARNED);
}

fn check(learned: bool, out: &str) {
    let s = suite(learned);
    aarnn_explorer::tasks::TaskSuite::parse(&s).expect("generated suite parses");
    if std::env::var_os("AARNN_EXPLORER_WRITE_FIXTURE").is_some() {
        std::fs::write(out, &s).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(out).expect("regenerate with AARNN_EXPLORER_WRITE_FIXTURE=1"),
        s,
        "stale; regenerate"
    );
}
