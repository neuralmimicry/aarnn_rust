//! Generator (and staleness check) of the Drosophila open-loop functional
//! contract from the body's IO contract, plus its learned-state extension
//! (`drosophila_learned.toml`: the same conditions and three that exercise
//! learned foraging, for a `derive --preset learned-cap` source). Regenerate with:
//! `AARNN_EXPLORER_WRITE_FIXTURE=1 cargo test -p aarnn-explorer --test gen_fly_suite`.
use std::fmt::Write;

const IO: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../sim/content/embodiments/generated/drosophila_banc.json"
);
const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../examples/explorer/tasks/drosophila_open_loop.toml"
);
const OUT_LEARNED: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../examples/explorer/tasks/drosophila_learned.toml"
);

fn suite(learned: bool) -> String {
    let io: serde_json::Value = serde_json::from_slice(&std::fs::read(IO).unwrap()).unwrap();
    let outputs: Vec<String> = io["io"]["output_names"]
        .as_array()
        .unwrap()
        .iter()
        .map(|x| x.as_str().unwrap().to_string())
        .collect();
    let mut s = String::new();
    s += "# SPDX-FileCopyrightText: masterkiga\n# SPDX-License-Identifier: MIT\n#\n# Licensed under the MIT License. See LICENSE in the project root.\n#\n";
    s +=
        "# GENERATED by crates/aarnn-explorer/tests/gen_fly_suite.rs from the drosophila_banc IO\n";
    s += "# contract. Open-loop functional contract of the designed Drosophila walking/\n";
    s += "# foraging circuit: in each condition, every one of the 48 motor outputs' mean\n";
    s += "# activation must stay within 10 % (+ 0.02) of the intact reference (cold start,\n";
    s += "# frozen plasticity). Conditions: walking, obstacles left/right (range 0.3, below\n";
    s += "# touch), touch left/right/front (escape pivot), feeding (halt) and hungry with a\n";
    s += "# left odour cue. A simulated-body contract, not a claim about fly behaviour.\n";
    if learned {
        s += "# Learned-state extension: hungry with a right cue, sated with a left cue (the\n";
        s += "# hunger gate) and a hungry cue that falls after 2 s (the value-fall turn).\n";
        s += "# Before learning these match the naive conditions; on a learned-state source\n";
        s += "# (aarnn-explorer derive --preset learned-cap) they exercise the value\n";
        s += "# readouts, steering and hunger gate that a naive frozen network never uses.\n";
    }
    let name = if learned {
        "drosophila-learned-v1"
    } else {
        "drosophila-open-loop-v1"
    };
    let _ = write!(
        s,
        "schema_version = 1\nname = \"{name}\"\n\n[splits]\ndevelopment = [1, 2, 3, 4]\nlocked_validation = [101, 102, 103, 104]\n"
    );
    let sated = "{ channel = \"needs_energy\", start_ms = 0, end_ms = 1000, value = 0.9 }";
    let mut tasks: Vec<(&str, &str, Vec<String>, (u32, u32))> = vec![
        ("walk", "discrimination", vec![sated.into()], (200, 1000)),
        ("obstacle-left", "discrimination", vec![sated.into(), "{ channel = \"dros_s_12_prox_02\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into(), "{ channel = \"dros_s_13_prox_03\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into()], (300, 800)),
        ("obstacle-right", "discrimination", vec![sated.into(), "{ channel = \"dros_s_32_prox_22\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into(), "{ channel = \"dros_s_31_prox_21\", start_ms = 300, end_ms = 800, value = 0.3, jitter = true }".into()], (300, 800)),
        ("touch-left", "timing", vec![sated.into(), "{ channel = \"dros_s_08_touch_left\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"dros_s_12_prox_02\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into()], (300, 1000)),
        ("touch-right", "timing", vec![sated.into(), "{ channel = \"dros_s_09_touch_right\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"dros_s_32_prox_22\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into()], (300, 1000)),
        ("touch-front", "timing", vec![sated.into(), "{ channel = \"dros_s_06_touch_front\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into(), "{ channel = \"dros_s_10_prox_00\", start_ms = 300, end_ms = 500, value = 0.6, jitter = true }".into()], (300, 1000)),
        ("feeding", "discrimination", vec![sated.into(), "{ channel = \"needs_consume\", start_ms = 300, end_ms = 700, value = 1.0, jitter = true }".into()], (300, 700)),
        ("hungry-cue-left", "discrimination", vec!["{ channel = \"needs_energy\", start_ms = 0, end_ms = 1000, value = 0.2 }".into(), "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.8 }".into(), "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.2 }".into()], (200, 1000)),
    ];
    if learned {
        let hungry = |ms: u32| {
            format!("{{ channel = \"needs_energy\", start_ms = 0, end_ms = {ms}, value = 0.2 }}")
        };
        tasks.push((
            "hungry-cue-right",
            "discrimination",
            vec![
                hungry(1000),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.8 }"
                    .into(),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.2 }".into(),
            ],
            (200, 1000),
        ));
        tasks.push((
            "sated-cue-left",
            "discrimination",
            vec![
                sated.into(),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 1000, value = 0.8 }".into(),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 1000, value = 0.2 }"
                    .into(),
            ],
            (200, 1000),
        ));
        tasks.push((
            "hungry-cue-fall",
            "timing",
            vec![
                hungry(3000),
                "{ channel = \"needs_cue_left\", start_ms = 0, end_ms = 2000, value = 0.8 }".into(),
                "{ channel = \"needs_cue_right\", start_ms = 0, end_ms = 2000, value = 0.8 }"
                    .into(),
                "{ channel = \"needs_cue_left\", start_ms = 2000, end_ms = 3000, value = 0.1 }"
                    .into(),
                "{ channel = \"needs_cue_right\", start_ms = 2000, end_ms = 3000, value = 0.1 }"
                    .into(),
            ],
            (2000, 3000),
        ));
    }
    for (id, fam, stim, (a, b)) in tasks {
        let dur = b.max(1000);
        let _ = write!(
            s,
            "\n[[task]]\nid = \"{id}\"\nfamily = \"{fam}\"\nduration_ms = {dur}\njitter_ms = 4\nstimulus = [\n"
        );
        for x in &stim {
            let _ = writeln!(s, "  {x},");
        }
        s += "]\nmeasure = [\n";
        for (k, o) in outputs.iter().enumerate() {
            let _ = writeln!(
                s,
                "  {{ name = \"m{k:02}\", output = \"{o}\", start_ms = {a}, end_ms = {b}, stat = \"mean\" }},"
            );
        }
        s += "]\ncriterion = [\n";
        for k in 0..outputs.len() {
            let _ = writeln!(
                s,
                "  {{ measure = \"m{k:02}\", op = \"within-reference\", amount = 0.1, value = 0.02 }},"
            );
        }
        s += "]\n";
    }
    s
}

fn check(learned: bool, out: &str) {
    let s = suite(learned);
    aarnn_explorer::tasks::TaskSuite::parse(&s).expect("generated suite parses");
    if std::env::var_os("AARNN_EXPLORER_WRITE_FIXTURE").is_some() {
        std::fs::write(out, &s).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(out).expect("regenerate with AARNN_EXPLORER_WRITE_FIXTURE=1"),
        s,
        "stale; regenerate"
    );
}

#[test]
fn drosophila_suite_is_current() {
    check(false, OUT);
}

#[test]
fn drosophila_learned_suite_is_current() {
    check(true, OUT_LEARNED);
}
