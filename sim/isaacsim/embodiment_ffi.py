"""ctypes view of the shared Rust embodiment ABI (crates/aarnn-embodiment-ffi).

The AER1 reference client, motor state machine and graded/pulse-density
decoders are the same Rust code the native MuJoCo owner links; nothing here
re-implements them. Signatures follow crates/aarnn-embodiment-ffi/include/
nm_embodiment.h (generated by scripts/generate_embodiment_ffi.py).
"""
import ctypes
import json
import os
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
ABI_VERSION = 1
CONTROL = {'auto': 0, 'npc': 1, 'silent': 2, 'aarnn': 3}
HYDRO_WIDTH = 21
_u8p = ctypes.POINTER(ctypes.c_uint8)
_f64p = ctypes.POINTER(ctypes.c_double)


def library_path():
    explicit = os.environ.get('NM_EMBODIMENT_FFI')
    if explicit:
        return Path(explicit)
    for candidate in (ROOT / 'target/isaacsim-ffi/release/libaarnn_embodiment_ffi.so',
                      ROOT / 'target/release/libaarnn_embodiment_ffi.so',
                      ROOT / 'target/debug/libaarnn_embodiment_ffi.so'):
        if candidate.is_file():
            return candidate
    raise FileNotFoundError('libaarnn_embodiment_ffi.so not built: CARGO_TARGET_DIR=target/isaacsim-ffi '
                            'cargo build --release --locked -p aarnn-embodiment-ffi')


def _load():
    lib = ctypes.CDLL(str(library_path()))
    sig = {
        'nm_embodiment_version': ([], ctypes.c_uint32),
        'nm_embodiment_error': ([_u8p, ctypes.c_uint32], ctypes.c_int32),
        'nm_reference_open': ([ctypes.c_char_p, ctypes.c_uint32, ctypes.c_char_p, ctypes.c_uint32,
                               ctypes.POINTER(ctypes.c_uint64)], ctypes.c_int32),
        'nm_reference_close': ([ctypes.c_uint64], ctypes.c_int32),
        'nm_reference_disarm': ([ctypes.c_uint64], ctypes.c_int32),
        'nm_reference_reset': ([ctypes.c_uint64], ctypes.c_int32),
        'nm_reference_apply': ([ctypes.c_uint64, ctypes.c_uint64, _f64p, ctypes.c_uint32, _f64p,
                                ctypes.c_uint32], ctypes.c_int32),
        'nm_reference_submit': ([ctypes.c_uint64, ctypes.c_uint64, _f64p, ctypes.c_uint32], ctypes.c_int32),
        'nm_reference_status': ([ctypes.c_uint64, _u8p, ctypes.c_uint32], ctypes.c_int32),
        'nm_control_mode': ([ctypes.c_uint64, ctypes.c_uint32], ctypes.c_int32),
        'nm_reference_motor_mask': ([ctypes.c_uint64, _u8p, ctypes.c_uint32], ctypes.c_int32),
        'nm_panel_forces': ([_f64p, ctypes.c_uint32, _f64p, ctypes.c_uint32], ctypes.c_int32),
        'nm_reference_hydro': ([ctypes.c_uint64, _f64p, ctypes.c_uint32, _f64p, ctypes.c_uint32], ctypes.c_int32),
    }
    for name, (args, ret) in sig.items():
        fn = getattr(lib, name)
        fn.argtypes, fn.restype = args, ret
    if lib.nm_embodiment_version() != ABI_VERSION:
        raise RuntimeError('embodiment ABI version mismatch')
    for name in ('nm_reference_apply', 'nm_reference_hydro'):
        if not hasattr(lib, name):
            raise RuntimeError(f'stale embodiment ABI without {name}: rebuild aarnn-embodiment-ffi')
    return lib


_LIB = None


def lib():
    global _LIB
    if _LIB is None:
        _LIB = _load()
    return _LIB


def _error():
    buffer = (ctypes.c_uint8 * 4096)()
    n = lib().nm_embodiment_error(buffer, 4096)
    return bytes(buffer[:max(n, 0)]).decode('utf-8', 'replace')


def _check(code, what):
    if code < 0:
        raise RuntimeError(f'{what}: {_error() or code}')
    return code


class Session:
    """One body's Rust reference session: AER1 client + shared motor decoder."""

    def __init__(self, model_xml, binding=None, control='auto'):
        path = str(Path(model_xml)).encode()
        payload = json.dumps(binding).encode() if binding else b''
        handle = ctypes.c_uint64(0)
        _check(lib().nm_reference_open(path, len(path), payload or None, len(payload), ctypes.byref(handle)),
               'nm_reference_open')
        self.handle = handle.value
        self.bound = binding is not None
        _check(lib().nm_control_mode(self.handle, CONTROL[control]), 'nm_control_mode')
        self._status = (ctypes.c_uint8 * 65536)()

    def apply(self, step, sensors, n_controls):
        sensors = np.ascontiguousarray(sensors, dtype=np.float64)
        out = np.zeros(n_controls, dtype=np.float64)
        code = lib().nm_reference_apply(self.handle, step, sensors.ctypes.data_as(_f64p), len(sensors),
                                        out.ctypes.data_as(_f64p), n_controls)
        return _check(code, 'nm_reference_apply'), out

    def submit(self, step, sensors):
        sensors = np.ascontiguousarray(sensors, dtype=np.float64)
        return _check(lib().nm_reference_submit(self.handle, step, sensors.ctypes.data_as(_f64p), len(sensors)),
                      'nm_reference_submit') == 1

    def motor_mask(self, n):
        buffer = (ctypes.c_uint8 * max(n, 1))()
        _check(lib().nm_reference_motor_mask(self.handle, buffer, n), 'nm_reference_motor_mask')
        return np.frombuffer(bytes(buffer[:n]), dtype=np.uint8).astype(bool)

    def status(self):
        n = _check(lib().nm_reference_status(self.handle, self._status, 65536), 'nm_reference_status')
        return json.loads(bytes(self._status[:n]))

    def hydro(self, rows):
        """Rows of HYDRO_WIDTH (see nm_reference_hydro) -> (n, 6) world force, torque."""
        rows = np.ascontiguousarray(rows, dtype=np.float64).reshape(-1, HYDRO_WIDTH)
        out = np.zeros(len(rows) * 6)
        _check(lib().nm_reference_hydro(self.handle, rows.ctypes.data_as(_f64p), len(rows),
                                        out.ctypes.data_as(_f64p), len(out)), 'nm_reference_hydro')
        return out.reshape(-1, 6)

    def disarm(self):
        if self.handle:
            lib().nm_reference_disarm(self.handle)

    def close(self):
        if self.handle:
            lib().nm_reference_disarm(self.handle)
            lib().nm_reference_close(self.handle)
            self.handle = 0


def panel_forces(inputs):
    """Batched dissipative panel forces (velocity, 3x3 rotation, area) -> world N."""
    inputs = np.ascontiguousarray(inputs, dtype=np.float64).reshape(-1, 13)
    out = np.zeros(len(inputs) * 3)
    _check(lib().nm_panel_forces(inputs.ctypes.data_as(_f64p), len(inputs), out.ctypes.data_as(_f64p), len(out)),
           'nm_panel_forces')
    return out.reshape(-1, 3)
